/**
 * dsh — minimal shell-style harness. It sources `.dshrc` and `DSH.md`, and
 * exposes hooks through `.dsh/hooks/*.sh`. We generate shell wrappers so the
 * hooks work even without JS-specific plumbing.
 */
export const dshAdapter: HarnessAdapter = {
  ...makeAdapter({
    id: 'dsh',
    displayName: 'dsh',
    configDir: '.dsh',
    rulesFile: 'DSH.md',
    mcpFile: null,
    events: ['start', 'prompt', 'stop', 'end'],
  }),
  artifacts(ctx: AdapterContext, opts: InstallOptions): InstallArtifact[] {
    const base = makeAdapter({
      id: 'dsh',
      displayName: 'dsh',
      configDir: '.dsh',
      rulesFile: 'DSH.md',
      mcpFile: null,
      events: ['start', 'prompt', 'stop', 'end'],
    }).artifacts(ctx, opts);

    const dir =
      opts.targetDir ??
      (opts.scope === 'global'
        ? path.join(homeDir(opts), '.dsh')
        : path.join(ctx.projectRoot, '.dsh'));
    for (const event of ['start', 'prompt', 'stop', 'end'] as const) {
      base.push({
        path: path.join(dir, 'hooks', `kb-${event}.sh`),
        strategy: 'write',
        content: [
          '#!/bin/sh',
          `# Generated by ${KB_MARKER}.`,
          '# stdin: harness payload JSON; stdout: text injected into the session.',
          `exec ${shQuote(ctx.nodeBin)} ${shQuote(ctx.cliEntry)} hook dsh ${event}`,
          '',
        ].join('\n'),
        marker: KB_MARKER,
      });
    }
    return base;
  },
};

function shQuote(s: string): string {
  return "'" + s.replace(/'/g, `'\\''`) + "'";
}

