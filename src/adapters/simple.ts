import path from 'node:path';
import {
  type AdapterContext,
  type HarnessAdapter,
  type HarnessId,
  type InstallArtifact,
  type InstallOptions,
  type KbHookEvent,
  KB_MARKER,
  homeDir,
  hookCommand,
  mcpServerSpec,
  obj,
  str,
} from './types.js';

export interface SimpleAdapterSpec {
  id: HarnessId;
  displayName: string;
  /** Config directory relative to the project root. */
  configDir: string;
  /** Rules file the harness always loads (relative to project root). */
  rulesFile: string;
  /**
   * Where the harness reads MCP servers, relative to the project root. `null`
   * means "not supported": only the rules file is installed.
   */
  mcpFile: string | null;
  /** Hook events the harness can actually fire. */
  events: Array<'start' | 'prompt' | 'stop' | 'end'>;
}

/**
 * Build an adapter for a harness whose hook surface is not publicly documented
 * in a stable form.
 *
 * The design rule: never emit a config key we cannot verify. Instead install
 * (a) a rules/instructions file the harness is known to read, which tells the
 * agent to call the MCP tool, and (b) an MCP registration only when the harness
 * documents an MCP server file. Lifecycle hooks are always written to our own
 * config so a harness that gains hook support later can point at
 * `kb hook <id> ...` without a rewrite.
 */
export function makeAdapter(spec: SimpleAdapterSpec): HarnessAdapter {
  return {
    id: spec.id,
    displayName: spec.displayName,
    verified: false,
    capabilities: {
      hooks: spec.events.length > 0,
      mcp: spec.mcpFile !== null,
      rulesFile: spec.rulesFile,
      configScope: 'project',
    },

    artifacts(ctx: AdapterContext, opts: InstallOptions): InstallArtifact[] {
      const out: InstallArtifact[] = [];
      const global = opts.scope === 'global';
      // Project install keeps config in the repo. Global install puts it under
      // `~/.<harness>/`, which is where these tools look when there is no
      // project-level config.
      const base =
        opts.targetDir ??
        (global ? path.join(homeDir(opts), spec.configDir) : path.join(ctx.projectRoot, spec.configDir));

      // Global installs keep the instruction file next to the config, because
      // writing into an arbitrary project's AGENTS.md from a global command
      // would surprise the user. These harnesses look for rules under `rules/`.
      const rulesPath = global
        ? path.join(base, 'rules', 'knowledge-base-harness.md')
        : path.join(ctx.projectRoot, spec.rulesFile);

      // A hook manifest in our own namespace: documented for humans and usable
      // by the harness once its hook syntax matches.
      const hooks: Record<string, string> = {};
      for (const event of spec.events) {
        const name = EVENT_NAMES[event];
        hooks[name] = hookCommand(ctx, spec.id, event);
      }
      out.push({
        path: path.join(base, `${KB_MARKER}.hooks.json`),
        strategy: 'write',
        content:
          JSON.stringify(
            {
              _comment: `Generated by ${KB_MARKER}. Wire these commands into ${spec.displayName}'s own hook/automation settings.`,
              harness: spec.id,
              hooks,
            },
            null,
            2,
          ) + '\n',
        marker: KB_MARKER,
      });

      if (spec.mcpFile) {
        out.push({
          path: global ? path.join(base, 'mcp.json') : path.join(ctx.projectRoot, spec.mcpFile),
          strategy: 'json-merge',
          content: JSON.stringify({ mcpServers: { kb: mcpServerSpec(ctx) } }, null, 2),
          marker: KB_MARKER,
          note: 'Registers the kb MCP server.',
        });
      }

      out.push({
        path: rulesPath,
        strategy: 'text-append',
        content: rulesBlock(spec, ctx),
        marker: KB_MARKER,
        note: 'Agent instructions: consult the wiki, record settled conclusions.',
      });

      return out;
    },

    parsePayload(raw: unknown): KbHookEvent | null {
      const o = obj(raw);
      const kindRaw = str(o, 'kind') ?? str(o, 'event') ?? str(o, 'hook_event_name');
      const kind = normaliseKind(kindRaw);
      if (!kind) return null;
      return {
        kind,
        harness: spec.id,
        cwd: str(o, 'cwd') ?? process.cwd(),
        prompt: str(o, 'prompt') ?? str(o, 'input') ?? str(o, 'message'),
        transcriptPath: str(o, 'transcript_path') ?? str(o, 'transcriptPath'),
        sessionId: str(o, 'session_id') ?? str(o, 'sessionId'),
        note: str(o, 'note'),
        raw,
      };
    },

    formatOutput(event, body): string {
      if ((event.kind === 'prompt' || event.kind === 'start') && body.context) {
        // Plain text is the widest-supported channel across these tools.
        return body.context;
      }
      return '';
    },
  };
}

const EVENT_NAMES: Record<string, string> = {
  start: 'sessionStart',
  prompt: 'userPromptSubmit',
  stop: 'agentStop',
  end: 'sessionEnd',
};

function normaliseKind(raw: string | undefined): KbHookEvent['kind'] | null {
  if (!raw) return null;
  const s = raw.toLowerCase().replace(/[_\s-]/g, '');
  if (['start', 'sessionstart', 'session_start', 'init'].includes(s)) return 'start';
  if (['prompt', 'userpromptsubmit', 'userprompt', 'promptsubmit', 'input'].includes(s)) return 'prompt';
  if (['stop', 'agentstop', 'turncomplete', 'agentend', 'response'].includes(s)) return 'stop';
  if (['end', 'sessionend', 'exit', 'quit', 'shutdown'].includes(s)) return 'end';
  if (['note', 'conclusion', 'kbnote'].includes(s)) return 'note';
  return null;
}

function rulesBlock(spec: SimpleAdapterSpec, ctx: AdapterContext): string {
  return [
    `<!-- >>> ${KB_MARKER} >>> -->`,
    `## Personal knowledge base (${spec.displayName})`,
    '',
    `A markdown wiki lives at \`${ctx.kbRoot}\`, maintained by ${KB_MARKER}.`,
    'It has an always-injected memory folder (`memory/MEMORY.md`, `memory/USER.md`)',
    'and an on-demand tree of topic pages.',
    '',
    '- **Before answering anything about this project**, query the wiki:',
    `  \`node "${ctx.cliEntry}" recall "<the user's question>"\` or the \`kb\` MCP tool.`,
    '- **When a conclusion is settled** (verified, decided, reproduced), record it:',
    `  \`node "${ctx.cliEntry}" note "<one-sentence conclusion>"\`.`,
    '  Add `--supersedes "<old text>"` when it replaces an earlier conclusion.',
    '- **Durable facts for every conversation** (environment quirks, conventions,',
    '  user preferences) go to memory, which has a hard size budget:',
    `  \`node "${ctx.cliEntry}" memory memory --add "<text>"\`.`,
    '- Procedures and pitfalls belong on a topic page, not in memory.',
    '- Never write transient notes, drafts, logs, TODOs or progress updates into the wiki.',
    `<!-- <<< ${KB_MARKER} <<< -->`,
    '',
  ].join('\n');
}

